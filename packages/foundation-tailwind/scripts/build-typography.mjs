import { writeFileSync, mkdirSync } from 'node:fs';

import { flattenTokens } from './utils/flatten-tokens.mjs';
import typographyTokensSource from '../tokens/Typography.tokens.json' with { type: 'json' };
import { tokenPathToCssVarName } from './utils/token-utils.mjs';

const typographyTokens = flattenTokens(typographyTokensSource);

const typographyClasses = Object.entries(typographyTokens).map(([name]) => {
  name = tokenPathToCssVarName(name);

  return [
    `.text-${name}`,
    {
      font: `var(--typography-${name}-font)`,
      letterSpacing: `var(--typography-${name}-letter-spacing)`,
    },
  ];
});

const typographyCategories = [
  ...new Set(
    Object.keys(typographyTokens).map((name) => {
      // Takes out individual categories
      // e.g. we have LabelSmall, and LabelMedium, only take Label out
      const category = name.match(/^[A-Z][a-z]+/);

      return category ? category[0] : null;
    }),
  ),
];
const typographyClassPrefixes = typographyCategories.map((category) => [
  `TTailwindText${category}`,
  `text-${tokenPathToCssVarName(category)}`,
]); // text-label, text-body, etc.

const typographyPluginBlock = `// !! This file is auto-generated by the build-typography.mjs script. Do not edit this file directly. !!
// !! To update the icons, run 'pnpm build:typography' in the foundation-tailwind package. !!

import plugin from 'tailwindcss/plugin';

export const typographyPlugin = plugin(function ({ addUtilities }) {
  addUtilities(${JSON.stringify(Object.fromEntries(typographyClasses), null, 2)});
})
`;

const typographyTypesBlock = `// !! This file is auto-generated by the build-typography.mjs script. Do not edit this file directly. !!
// !! To update the icons, run 'pnpm build:typography' in the foundation-tailwind package. !!
${typographyClassPrefixes
  .map(([typeName, classPrefix]) => {
    return `export type ${typeName}Prefix = '${classPrefix}';`;
  })
  .join('\n')}

export type TTailwindTextValue =
  | 'small'
  | 'medium'
  | 'large';

${typographyClassPrefixes
  .map(([typeName]) => {
    return `export type ${typeName}Class = \`\${${typeName}Prefix}-\${TTailwindTextValue}\`;`;
  })
  .join('\n')}

export type TTailwindTextClass =
  ${typographyClassPrefixes
    .map(([typeName]) => {
      return `${typeName}Class`;
    })
    .join(' | \n  ')};
`;

mkdirSync('./src/preset/plugins', {
  recursive: true,
});
mkdirSync('./src/classes', {
  recursive: true,
});
writeFileSync(
  './src/preset/plugins/typography.generated.ts',
  typographyPluginBlock,
);
writeFileSync('./src/classes/typography.generated.ts', typographyTypesBlock);
// oxlint-disable-next-line no-console
console.log(
  `Wrote ./src/preset/plugins/typography.generated.ts and ./src/classes/typography.generated.ts with ${typographyClasses.length} typography classes.`,
);
